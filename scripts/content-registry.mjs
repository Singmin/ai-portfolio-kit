import { existsSync, readFileSync, readdirSync, writeFileSync, realpathSync, statSync, watch } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { z } from 'zod';
import { postSchema } from '../src/content/post-schema.mjs';
import { extractPassages } from './extract-passages.mjs';

export function publicAsset(root, url, field) {
  let pathname;
  try { pathname = decodeURIComponent(url.split(/[?#]/)[0]); } catch { throw new Error(`${field}: invalid URL encoding`); }
  if (!/^\/(?!\/)/.test(pathname) || /\\|(?:^|\/)\.\.(?:\/|$)/.test(pathname)) throw new Error(`${field}: use a local public/ path`);
  const directory = realpathSync(path.join(root, 'public'));
  const target = path.resolve(directory, `.${pathname}`);
  const inside = candidate => candidate.startsWith(directory + path.sep);
  if (!inside(target) || !existsSync(target) || !inside(realpathSync(target)) || !statSync(target).isFile()) throw new Error(`${field}: missing or unsafe public asset ${url}`);
}

export function readRegistry(root) {
  const directory = path.join(root, 'src/content/posts');
  const records = [];
  const registered = new Set();
  for (const file of readdirSync(directory).filter(file => file.endsWith('.json')).sort()) {
    const field = `src/content/posts/${file}`;
    let raw;
    try { raw = JSON.parse(readFileSync(path.join(directory, file), 'utf8')); }
    catch (error) { throw new Error(`${field}: ${error.message}`); }
    const result = postSchema.safeParse(raw);
    if (!result.success) throw new Error(result.error.issues.map(issue => `${field}.${issue.path.join('.')}: ${issue.message}`).join('\n'));
    const post = result.data;
    const passages = {};
    if (records.some(item => item.slug === post.slug)) throw new Error(`${field}.slug: duplicate ${post.slug}`);
    if (file !== `${post.slug}.json`) throw new Error(`${field}.slug: filename must be ${post.slug}.json`);
    for (const locale of Object.keys(post.translations)) {
      const source = `${post.slug}.${locale}.mdx`;
      if (!existsSync(path.join(directory, source))) throw new Error(`${field}.translations.${locale}: missing ${source}`);
      // MDX is executable, trusted repository code. This is link linting, not a sandbox.
      const body = readFileSync(path.join(directory, source), 'utf8');
      if (post.status === 'published' && post.aiIndex === true) {
        passages[locale] = extractPassages(body, source);
        if (!passages[locale].length) throw new Error(`${source}.aiIndex: mark at least one static paragraph with PublicExcerpt`);
      }
      registered.add(source);
      const links = [...body.matchAll(/(!?)\[[^\]]*\]\(([^\s)]+)(?:\s+"[^"]*")?\)/g)]
        .map(match => ({ image: !!match[1], url: match[2] }));
      for (const match of body.matchAll(/\b(href|src)\s*=\s*["']([^"']+)["']/g)) links.push({ image: match[1] === 'src', url: match[2] });
      for (const { image, url } of links) {
        if (image) publicAsset(root, url, `${source}.media`);
        else {
          let valid = /^(?:\/(?!\/)|#)/.test(url) && !/[\\\s]/.test(url);
          try {
            const parsed = new URL(url);
            valid ||= ['http:', 'https:'].includes(parsed.protocol) || (parsed.protocol === 'mailto:' && z.email().safeParse(parsed.pathname).success);
          } catch { /* Relative routes and fragments were checked above. */ }
          if (!valid) throw new Error(`${source}.links: invalid URL ${url}`);
        }
      }
    }
    records.push({ ...post, ...(Object.keys(passages).length ? { passages } : {}) });
  }
  for (const file of readdirSync(directory).filter(file => file.endsWith('.mdx'))) {
    if (!registered.has(file)) throw new Error(`src/content/posts/${file}: unregistered MDX; add its translation to a post JSON file`);
  }
  return records.sort((a, b) => b.date.localeCompare(a.date) || a.slug.localeCompare(b.slug));
}

export function generateRegistry(root) {
  const posts = readRegistry(root);
  const save = (file, body) => {
    const target = path.join(root, 'src/content', file);
    if (!existsSync(target) || readFileSync(target, 'utf8') !== body) writeFileSync(target, body);
  };
  save('post-metadata.ts', `// Generated by scripts/content-registry.mjs. Edit posts/*.json instead.\nimport type { PostMetadata } from './post-model';\nexport type { PostMetadata } from './post-model';\nexport const postMetadata: PostMetadata[] = ${JSON.stringify(posts.filter(post => post.status !== 'draft'), null, 2)};\n`);
  const entries = posts.filter(post => post.status !== 'draft').flatMap(post => Object.keys(post.translations).map(locale =>
    `  '${post.slug}:${locale}': () => import('./posts/${post.slug}.${locale}.mdx'),`));
  save('post-loaders.ts', `// Generated; drafts are never imported. Trusted local MDX only.\nimport type { ComponentType } from 'react';\nexport const postLoaders: Record<string, () => Promise<{ default: ComponentType }>> = {\n${entries.join('\n')}\n};\n`);
  return posts;
}

// Watch only the explicit, flat public post directory. No private folders or URLs.
const watcherKey = Symbol.for('portfolio.contentWatcher');
export function watchRegistry(root) {
  globalThis[watcherKey]?.close();
  let timer;
  const watcher = watch(path.join(root, 'src/content/posts'), { persistent: false }, () => {
    clearTimeout(timer);
    timer = setTimeout(() => {
      try { generateRegistry(root); }
      catch (error) {
        // Fail closed during an invalid edit: never retain stale authorized excerpts.
        writeFileSync(path.join(root, 'src/content/post-metadata.ts'), "import type { PostMetadata } from './post-model';\nexport type { PostMetadata } from './post-model';\nexport const postMetadata: PostMetadata[] = [];\n");
        writeFileSync(path.join(root, 'src/content/post-loaders.ts'), "import type { ComponentType } from 'react';\nexport const postLoaders: Record<string, () => Promise<{ default: ComponentType }>> = {};\n");
        console.error(`Content registry: ${error.message}`);
      }
    }, 80);
    timer.unref();
  });
  globalThis[watcherKey] = { close: () => { clearTimeout(timer); watcher.close(); } };
  return globalThis[watcherKey];
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const posts = generateRegistry(process.cwd());
  console.log(`Content registry: ${posts.length} records validated (${posts.filter(post => post.status === 'draft').length} drafts excluded).`);
}
